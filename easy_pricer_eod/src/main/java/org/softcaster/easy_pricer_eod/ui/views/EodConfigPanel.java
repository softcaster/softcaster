    private void findBySbcId() {
        sbc = eodFacade.getSystemBusinessCalendarDAO().findBySbcId(1);
    }

    private void setUpCombos() {
        setUpCalendarCombo();
        setUpCurrencyCombo();
    }

    private void setUpCalendarCombo() {
        List<Calendar> calendars = eodFacade.getCalendarDAO().findAll();

        // 2. Crea il modello partendo dalla lista
        DefaultComboBoxModel<Calendar> model = new DefaultComboBoxModel<>(calendars.toArray(Calendar[]::new));
        cbCalendar.setModel(model);

    }

    private void setUpCurrencyCombo() {
        List<Currency> currencies = eodFacade.getCurrencyDAO().findAll();

        // 2. Crea il modello partendo dalla lista
        DefaultComboBoxModel<Currency> model = new DefaultComboBoxModel<>(currencies.toArray(Currency[]::new));
        cbCurrency.setModel(model);

    }

    private void updateFields() {
        txtDescription.setText(sbc.getDescription());
        cbCurrency.setSelectedItem(sbc.getCurrency());
        cbCalendar.setSelectedItem(sbc.getCalendar());
        java.sql.Date sqlDate = java.sql.Date.valueOf(sbc.getLastOfficialDate());
        Date dt = new Date(sqlDate);
        txtLastOfficialDate.setText(dt.toString());
        txtLastOfficialDate.setEnabled(false);
        sqlDate = java.sql.Date.valueOf(sbc.getOfficialDate());
        dt = new Date(sqlDate);
        txtOfficialDate.setText(dt.toString());
        if (sbc.getNextBusinessDate() != null) {
            sqlDate = java.sql.Date.valueOf(sbc.getNextBusinessDate());
            dt = new Date(sqlDate);
            txtNextOfficialDate.setText(dt.toString());
        }
        txtStatus.setText(sbc.getStatus().getDescription());
        if (sbc.getStatus() != SbcStatus.OPEN) {
            txtDescription.setEnabled(false);
            cbCurrency.setEnabled(false);
            cbCalendar.setEnabled(false);
            txtOfficialDate.setEnabled(false);
            txtNextOfficialDate.setEnabled(false);
            btnSave.setEnabled(false);
        }
    }
