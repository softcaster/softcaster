    @Override
    protected void acModActionPerformed(ActionEvent evt) {
        int rowIndex = servicesTable.getSelectedRow();
        if (rowIndex != -1) {
            // 1. CONVERSIONE FONDAMENTALE
            int modelRow = servicesTable.convertRowIndexToModel(rowIndex);
            DescriptorsTableModel model = (DescriptorsTableModel) servicesTable.getModel();
            DescriptorBean bean = model.getElementAt(modelRow);
            java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(this);
            java.awt.Frame parentFrame = null;

            if (parentWindow instanceof java.awt.Frame frame) {
                parentFrame = frame;
            }

            ServiceSetupDlg dialog = new ServiceSetupDlg(parentFrame, true, bean, eodFacade);
            dialog.setSize(425, 250);
            // Centra la dialog rispetto al pannello
            dialog.setLocationRelativeTo(this);
            dialog.setVisible(true);

            // Post chiusura dialog
            if (dialog.isConfirmed()) {
                refreshModelFromDb(model);
            }
        }
    }

