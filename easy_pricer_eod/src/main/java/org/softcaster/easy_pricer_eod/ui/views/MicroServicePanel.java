    @Override
    protected void fillModelList() {
        // Crea e setta il model
        DescriptorBean prototype = new DescriptorBean(null);
        DescriptorsTableModel model = new DescriptorsTableModel(prototype);
        servicesTable.setModel(model);

        // Popola il model
        refreshModelFromDb(model);
    }

    protected void refreshModelFromDb(FndtTableModel ftm) {
        // Cancella vecchia lista
        descriptorsList.clear();

        // Leggo lista pairs anagrafiche
        List<Descriptors> descriptorList = eodFacade.getDescriptorsDAO().findAll();
        if (descriptorList.isEmpty()) {
            return;
        }

        DescriptorBean bean = null;
        for (Descriptors descriptor : descriptorList) {
            bean = new DescriptorBean(descriptor);
            descriptorsList.add(bean);
        }

        ftm.setData(descriptorsList);
    }

