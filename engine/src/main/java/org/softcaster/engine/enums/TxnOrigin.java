package org.softcaster.engine.enums;

/**
 * Chi ha creato la transazione (financial_txn.txn_origin): gli utenti dal deal
 * capture o la chiusura di giornata.
 */
public enum TxnOrigin implements IdentifiableEnum {
    USER(1, "USER", "Entered by a user"),
    EOD(2, "EOD", "Generated by the end of day");

    private final int id;
    private final String code;
    private final String description;

    TxnOrigin(int id, String code, String description) {
        this.id = id;
        this.code = code;
        this.description = description;
    }

    @Override
    public int getId() {
        return id;
    }

    @Override
    public String getCode() {
        return code;
    }

    @Override
    public String getDescription() {
        return description;
    }

    public static TxnOrigin fromId(int id) {
        return IdentifiableEnum.fromId(TxnOrigin.class, id);
    }

    public static TxnOrigin fromCode(String code) {
        return IdentifiableEnum.fromCode(TxnOrigin.class, code);
    }
}
