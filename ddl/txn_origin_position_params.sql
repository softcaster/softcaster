-- ============================================================================
-- Parametri della posizione e origine della transazione
--
-- position_master_data:
--   fx_rolling      gli spot FX della posizione si rollano a ogni chiusura
--                   invece di regolare a T+2 (default: no)
--   bond_valuation  criterio di valutazione dei titoli della posizione
--                   (default: FAIR_VALUE, il comportamento attuale)
--
-- financial_txn:
--   txn_origin      chi ha creato il deal: USER (deal capture), EOD (chiusura)
--   origin_key      chiave del deal generato da un processo, con il processo
--                   come prefisso (es. FX_ROLL:<position_detail>:<data>:CLOSE);
--                   vuota per i deal degli utenti. Univoca: un rilancio del
--                   processo non genera doppioni.
--
-- Enum Java: BondValuation, TxnOrigin. Riportata in sofie.sql e sofie_startup.sql.
-- ============================================================================

BEGIN;

CREATE TABLE bond_valuation (
    bond_valuation_id  INTEGER NOT NULL,
    code               VARCHAR(25) NOT NULL,
    description        VARCHAR(64) NOT NULL,
    CONSTRAINT pk_bond_valuation PRIMARY KEY (bond_valuation_id),
    CONSTRAINT uq_bond_valuation_code UNIQUE (code)
);
ALTER TABLE bond_valuation OWNER TO sofie;

INSERT INTO bond_valuation VALUES (1, 'FAIR_VALUE', 'Fair value');
INSERT INTO bond_valuation VALUES (2, 'AMORTIZED_COST', 'Amortized cost');

ALTER TABLE position_master_data
    ADD COLUMN fx_rolling BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN bond_valuation INTEGER NOT NULL DEFAULT 1,
    ADD CONSTRAINT fk_position_bond_valuation
        FOREIGN KEY (bond_valuation) REFERENCES bond_valuation (bond_valuation_id);

CREATE TABLE txn_origin (
    txn_origin_id  INTEGER NOT NULL,
    code           VARCHAR(25) NOT NULL,
    description    VARCHAR(64) NOT NULL,
    CONSTRAINT pk_txn_origin PRIMARY KEY (txn_origin_id),
    CONSTRAINT uq_txn_origin_code UNIQUE (code)
);
ALTER TABLE txn_origin OWNER TO sofie;

INSERT INTO txn_origin VALUES (1, 'USER', 'Entered by a user');
INSERT INTO txn_origin VALUES (2, 'EOD', 'Generated by the end of day');

ALTER TABLE financial_txn
    ADD COLUMN txn_origin INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN origin_key VARCHAR(100),
    ADD CONSTRAINT fk_txn_origin FOREIGN KEY (txn_origin) REFERENCES txn_origin (txn_origin_id),
    ADD CONSTRAINT uq_financial_txn_origin_key UNIQUE (origin_key);

COMMIT;
