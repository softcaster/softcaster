    @Override
    protected void updateModel(FndtTableModel model) {
        if (model != null) {
            CalibrationProfileBean bean = null;
            ZSpreadHelper zSpreadHelper = mDSFacade.getzSpreadHelper();
            if (zSpreadHelper != null) {
                for (int i = 0; i < model.getRowCount(); i++) {
                    bean = (CalibrationProfileBean) model.getElementAt(i);
                    if (bean != null) {
                        zSpreadHelper.updateCalibrationItems(bean.getBean().getCode());
                        zSpreadHelper.calibrateZSpreadCurves(bean.getBean().getCalibrationProfileId());
                    }
                }
            }

        }

    }

    protected void refreshModelFromDb(FndtTableModel ftm) {
        // Cancella vecchia lista
        calibrationProfileBeanList.clear();

        // Leggo lista calibration profile
        List<CalibrationProfile> cpList = mDSFacade.getCalibrationProfileDAO().findAll();
        if (cpList == null || cpList.isEmpty()) {
            return;
        }

        CalibrationProfileBean bean = null;
        for (CalibrationProfile item : cpList) {
            bean = new CalibrationProfileBean(item);
            calibrationProfileBeanList.add(bean);
        }

        ftm.setData(calibrationProfileBeanList);
    }
