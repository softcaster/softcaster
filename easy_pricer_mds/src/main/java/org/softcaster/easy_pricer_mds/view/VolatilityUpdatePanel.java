    @Override
    protected void refreshModel(FndtTableModel ftm) {
        // 1. Crea la dialog di attesa
        final JDialog loadingDialog = createLoadingDialog("Updating volatilities ... Please wait.");

        // 2. Crea lo SwingWorker
        SwingWorker<Void, Void> worker = new SwingWorker<Void, Void>() {

            @Override
            protected Void doInBackground() throws Exception {
                // Questo metodo gira su un THREAD SEPARATO in background.
                updateModel(ftm);
                return null;
            }

            @Override
            protected void done() {
                // Questo metodo viene eseguito sull'EDT (Thread Grafico) alla fine del batch.
                java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(VolatilityUpdatePanel.this);
                try {
                    get();
                    // nuove date di rilevazione
                    refreshModelFromDb(ftm);
                    javax.swing.JOptionPane.showMessageDialog(parentWindow, summary,
                            "Volatility Update", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                } catch (InterruptedException | ExecutionException e) {
                    LoggerMgr.logError(e.getLocalizedMessage());
                    javax.swing.JOptionPane.showMessageDialog(parentWindow,
                            "Error during volatility update: " + e.getLocalizedMessage(),
                            "Volatility Update", javax.swing.JOptionPane.ERROR_MESSAGE);
                } finally {
                    // Chiude la dialog e sblocca la Card del pannello
                    loadingDialog.dispose();
                }
            }
        };
        // 3. Avvia il thread in background
        worker.execute();
        // 4. Mostra la dialog (bloccherà solo l'interfaccia, non il thread in background)
        loadingDialog.setVisible(true);
    }

