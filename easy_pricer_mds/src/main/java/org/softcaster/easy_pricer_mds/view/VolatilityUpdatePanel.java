    /**
     * Importa le superfici configurate della tabella dal CSV CME piu' recente
     * della cartella. Un errore su una superficie non ferma le altre.
     */
    @Override
    protected void updateModel(FndtTableModel model) {
        String directory = mDSFacade.getCmeDirectory();
        if (directory == null || directory.isBlank()) {
            summary = "Volatility import not configured: set CME_VOL_DIRECTORY in conf/params.xml.";
            return;
        }
        Path file;
        try {
            file = VolatilityImportHelper.latestFile(Path.of(directory));
        } catch (RuntimeException e) {
            LoggerMgr.logError(e.getLocalizedMessage());
            summary = e.getLocalizedMessage();
            return;
        }
        StringBuilder sb = new StringBuilder("Volatility import from " + file.getFileName() + ":");
        int imported = 0;
        if (model != null) {
            for (int i = 0; i < model.getRowCount(); i++) {
                VolatilitySurfaceBean bean = (VolatilitySurfaceBean) model.getElementAt(i);
                if (bean == null || !bean.isConfigured()) {
                    continue;
                }
                String code = bean.getBean().getCode();
                try {
                    VolatilityImportHelper.ImportResult r = mDSFacade.getVolatilityImportHelper().importCmeSettlements(
                            code, file, bean.getOptionSymbol(), bean.getFutureSymbol(), bean.getStrikeScale(), MIN_PREMIUM);
                    sb.append("\n- ").append(r.describe());
                } catch (RuntimeException e) {
                    LoggerMgr.logError(e.getLocalizedMessage());
                    sb.append("\n- ").append(code).append(": ").append(e.getLocalizedMessage());
                }
                imported++;
            }
        }
        if (imported == 0) {
            sb.append("\n- no surface configured in CME_VOL_SURFACES (conf/params.xml)");
        }
        summary = sb.toString();
    }

    protected void refreshModelFromDb(FndtTableModel ftm) {
        // Cancella vecchia lista
        volatilitySurfaceBeanList.clear();

        // Leggo lista superfici
        List<VolatilitySurfaceEntity> surfaces = mDSFacade.getVolatilitySurfaceDAO().findAll();
        if (surfaces == null || surfaces.isEmpty()) {
            ftm.setData(volatilitySurfaceBeanList);
            return;
        }

        Map<String, String[]> cme = cmeSymbols();
        LocalDate any = LocalDate.of(9999, 12, 31);
        for (VolatilitySurfaceEntity s : surfaces) {
            String[] symbols = cme.get(s.getCode());
            LocalDate last = mDSFacade.getVolatilitySurfaceDAO().findLastReferenceDate(s.getIdVolatilitySurface(), any)
                    .orElse(null);
            volatilitySurfaceBeanList.add(new VolatilitySurfaceBean(s,
                    s.getUnderlying() == null ? "" : s.getUnderlying().getCode(), last,
                    symbols == null ? null : symbols[1], symbols == null ? null : symbols[2],
                    symbols != null && symbols.length > 3 ? Double.parseDouble(symbols[3]) : 1.));
        }

        ftm.setData(volatilitySurfaceBeanList);
    }

    /**
     * CME_VOL_SURFACES (conf/params.xml): superficie:opzione:future[:strikeScale],
     * separati da virgola, per codice di superficie.
     */
    private Map<String, String[]> cmeSymbols() {
        Map<String, String[]> map = new HashMap<>();
        String surfaces = mDSFacade.getCmeSurfaces();
        if (surfaces == null || surfaces.isBlank()) {
            return map;
        }
        for (String entry : surfaces.split(",")) {
            String[] parts = entry.trim().split(":");
            if (parts.length >= 3) {
                map.put(parts[0].trim(), parts);
            } else {
                LoggerMgr.logError("CME_VOL_SURFACES: expected surface:option:future[:strikeScale], found " + entry);
            }
        }
        return map;
    }
