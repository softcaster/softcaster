    private boolean saveBean() {
        try {
            if (isInsert) {
                bean = new YieldCurveBean(new YieldCurveEntity());
                bean.getYieldCurve().setCode(txtCode.getText());
                bean.getYieldCurve().setDescription(txtDescription.getText());
                bean.getYieldCurve().setCurrency((Currency) cbCurrency.getSelectedItem());
                bean.getYieldCurve().setCalendar((Calendar) cbCalendar.getSelectedItem());
                bean.getYieldCurve().setProvider((String) cbProvider.getSelectedItem());
                bean.getYieldCurve().setCompounding((short)Compounding.CONTINUOUS.getId());
            } else {

            }
            mDSFacade.getYieldCurveDAO().saveOrUpdate(bean.getYieldCurve());
            return true;
        } catch (Exception ex) {
            LoggerMgr.logError(ex.getLocalizedMessage());
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error saving Yield Curve", // Messaggio
                    "Save Error", // Titolo
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }

    private void postInit() {
        setUpBondsCombo();

        if (bean != null) {
            isInsert = false;
            txtCode.setText(bean.getYieldCurve().getCode());
            txtDescription.setText(bean.getYieldCurve().getDescription());
            cbCurrency.setSelectedItem(bean.getYieldCurve().getCurrency());
            cbCalendar.setSelectedItem(bean.getYieldCurve().getCalendar());
            cbProvider.setSelectedItem(bean.getYieldCurve().getProvider());
        } else {
            txtCode.setText("");
            txtDescription.setText("");
        }
    }

    private void setUpBondsCombo() {
        setUpCurrencyCombo();
        setUpCalendarCombo();
    }

    private void setUpCurrencyCombo() {
        List<Currency> currencies = mDSFacade.getCurrencyDAO().findAll();

        // 2. Crea il modello partendo dalla lista
        DefaultComboBoxModel<Currency> model = new DefaultComboBoxModel<>(currencies.toArray(Currency[]::new));
        cbCurrency.setModel(model);
    }

    private void setUpCalendarCombo() {
        List<Calendar> calendar = mDSFacade.getCalendarDAO().findAll();

        // 2. Crea il modello partendo dalla lista
        DefaultComboBoxModel<Calendar> model = new DefaultComboBoxModel<>(calendar.toArray(Calendar[]::new));
        cbCalendar.setModel(model);
    }
