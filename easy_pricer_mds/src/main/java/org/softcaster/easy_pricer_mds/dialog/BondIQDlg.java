    private void brnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_brnSaveActionPerformed
        boolean isValid = validateFields() && validateIntegrity();

        if (!isValid) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please check all the required fields.", // Messaggio
                    "Validation Error", // Titolo
                    javax.swing.JOptionPane.ERROR_MESSAGE);

        } else {
            if (!saveBean()) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Error during save.\n See log file for more details.", // Messaggio
                        "Save Error", // Titolo
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            confirmed = true;
            this.dispose();
        }

        this.dispose();
    }//GEN-LAST:event_brnSaveActionPerformed

