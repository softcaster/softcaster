    private void postInit() {
        setUpBondsCombo();

        if (bean != null) {
            isInsert = false;
            txtCode.setText(bean.getInstrumentQuote().getCode());
            cbBond.setSelectedItem(bean.getInstrumentQuote().getMasterData());
            txtBid.setText(Converter.fromDouble(bean.getBid()));
            txtAsk.setText(Converter.fromDouble(bean.getAsk()));
            cbProvider.setSelectedItem(bean.getInstrumentQuote().getProvider());
        } else {
            txtBid.setText(Converter.fromDouble(0.));
            txtAsk.setText(Converter.fromDouble(0.));
        }

        // Aggiungo i campi alla lista di validazione
        fieldsToValidate = Arrays.asList(txtCode, txtBid, txtAsk);

        // Aggiusto i campi
        txtCode.setColumns(10);
        txtBid.setColumns(10);
        txtAsk.setColumns(10);
    }

    private void setUpBondsCombo() {
        List<SecurityMasterData> bondList = mDSFacade.getSecurityMasterDataDAO().findAll();

        // 2. Crea il modello partendo dalla lista
        DefaultComboBoxModel<SecurityMasterData> model = new DefaultComboBoxModel<>(bondList.toArray(SecurityMasterData[]::new));
        cbBond.setModel(model);

    }

    private boolean validateFields() {
        return DialogHelper.validateFields(fieldsToValidate);
    }

    private boolean validateIntegrity() {
        return true;
    }

    private boolean saveBean() {
        try {
            if (isInsert) {
                bean = new BondBean(new InstrumentQuote());
            }
            InstrumentQuote iq = bean.getInstrumentQuote();
            iq.setMasterData((MasterData) cbBond.getSelectedItem());
            iq.setCode(txtCode.getText());
            iq.setBid(Converter.toDouble(txtBid.getText(), false));
            iq.setAsk(Converter.toDouble(txtAsk.getText(), false));
            iq.setProvider(cbProvider.getSelectedItem().toString());
            mDSFacade.getInstrumentQuoteDAO().saveOrUpdate(iq);
            return true;
        } catch (Exception ex) {
            LoggerMgr.logError(ex.getLocalizedMessage());
            return false;
        }
    }
