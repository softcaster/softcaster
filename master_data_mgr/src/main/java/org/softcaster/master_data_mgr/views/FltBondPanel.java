    @Override
    protected void fillModelList() {
        // Crea e setta il model
        FltSecurityBean prototype = new FltSecurityBean(null);
        MasterDataTableModel<FltSecurityBean> model = new MasterDataTableModel<>(prototype);
        bondTable.setModel(model);

        // Popola il model
        refreshModel(model);
    }

    @Override
    protected void refreshModel(MasterDataTableModel model) {
        List<FltSecurityMasterData> bonds = masterDataFacade.getFltSecurityMasterDataDAO().findAll();
        List<FltSecurityBean> securityBeanList = new ArrayList<>();
        FltSecurityBean bean = null;
        for (FltSecurityMasterData item : bonds) {
            bean = new FltSecurityBean(item);
            securityBeanList.add(bean);
        }
        model.setData(securityBeanList);
    }

    @Override
    protected void acNewActionPerformed(ActionEvent evt) {
        java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(this);
        java.awt.Frame parentFrame = null;

        if (parentWindow instanceof java.awt.Frame frame) {
            parentFrame = frame;
        }

        FltBondDlg dialog = new FltBondDlg(parentFrame, true, null, masterDataFacade);
        dialog.setSize(600, 400);
        // Centra la dialog rispetto al pannello
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        // Post chiusura dialog
        MasterDataTableModel<FltSecurityBean> model = (MasterDataTableModel<FltSecurityBean>) bondTable.getModel();
        refreshModel(model);
    }

