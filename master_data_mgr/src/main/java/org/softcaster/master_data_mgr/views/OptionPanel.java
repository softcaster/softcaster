    @Override
    protected void fillModelList() {
        // Crea e setta il model
        OptionBean prototype = new OptionBean(null);
        OptionTableModel model = new OptionTableModel(prototype);
        optionTable.setModel(model);

        // Popola il model
        refreshModel(model);
    }

    @Override
    protected void acNewActionPerformed(ActionEvent evt) {
        openDialog(null);
    }

    @Override
    protected void acModActionPerformed(ActionEvent evt) {
        int rowIndex = optionTable.getSelectedRow();
        if (rowIndex != -1) {
            int modelRow = optionTable.convertRowIndexToModel(rowIndex);
            OptionTableModel model = (OptionTableModel) optionTable.getModel();
            openDialog(model.getElementAt(modelRow));
        }
    }

    /**
     * Finestra del ramo: FutureOptionDlg (codice e ISIN CME) o SpotOptionDlg.
     */
    private void openDialog(OptionBean bean) {
        java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(this);
        java.awt.Frame parentFrame = null;

        if (parentWindow instanceof java.awt.Frame frame) {
            parentFrame = frame;
        }

        javax.swing.JDialog dialog = branch == Branch.FUTURE
                ? new FutureOptionDlg(parentFrame, true, bean, masterDataFacade, assetClasses)
                : new SpotOptionDlg(parentFrame, true, bean, masterDataFacade, assetClasses);
        dialog.setSize(640, 420);
        // Centra la dialog rispetto al pannello
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        // Post chiusura dialog
        refreshModel((OptionTableModel) optionTable.getModel());
    }

