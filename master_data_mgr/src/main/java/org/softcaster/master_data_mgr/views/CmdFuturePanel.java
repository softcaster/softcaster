    @Override
    protected void fillModelList() {
        // Crea e setta il model
        CmdFutBean prototype = new CmdFutBean(null);
        CmdFutTableModel model = new CmdFutTableModel(prototype);
        cmdFutTable.setModel(model);

        // Popola il model
        refreshModel(model);
    }

    @Override
    protected void acNewActionPerformed(ActionEvent evt) {
        java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(this);
        java.awt.Frame parentFrame = null;

        if (parentWindow instanceof java.awt.Frame frame) {
            parentFrame = frame;
        }

        CmdFutureDlg dialog = new CmdFutureDlg(parentFrame, true, null, masterDataFacade);
        dialog.setSize(600, 400);
        // Centra la dialog rispetto al pannello
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
        
        // Post chiusura dialog
        CmdFutTableModel model = (CmdFutTableModel) cmdFutTable.getModel();
        refreshModel(model);
    }

    @Override
    protected void acModActionPerformed(ActionEvent evt) {
        int rowIndex = cmdFutTable.getSelectedRow();
        if (rowIndex != -1) {
            java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(this);
            java.awt.Frame parentFrame = null;

            if (parentWindow instanceof java.awt.Frame frame) {
                parentFrame = frame;
            }

            // 1. CONVERSIONE FONDAMENTALE
            int modelRow = cmdFutTable.convertRowIndexToModel(rowIndex);
            CmdFutTableModel model = (CmdFutTableModel) cmdFutTable.getModel();
            CmdFutBean bean = model.getElementAt(modelRow);

            CmdFutureDlg dialog = new CmdFutureDlg(parentFrame, true, bean, masterDataFacade);
            dialog.setSize(600, 300);
            // Centra la dialog rispetto al pannello
            dialog.setLocationRelativeTo(this);
            dialog.setVisible(true);

            // Post chiusura dialog
            refreshModel(model);

        }
    }

