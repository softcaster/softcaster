    @Override
    protected void refreshModel(FndtTableModel ftm) {
        // Popola il model
        List<CmdFutureMasterData> cmdFutures = masterDataFacade.getCmdFutureMasterDataDAO().findAll();

        List<CmdFutBean> cmsFutBeanList = new ArrayList<>();
        CmdFutBean bean = null;
        for (CmdFutureMasterData item : cmdFutures) {
            bean = new CmdFutBean(item);
            cmsFutBeanList.add(bean);
        }
        ftm.setData(cmsFutBeanList);
    }

