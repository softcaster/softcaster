    @Override
    protected void refreshModel(FndtTableModel ftm) {
        List<FutureProductBean> beans = new ArrayList<>();
        for (FutureProduct item : masterDataFacade.getFutureProductDAO().findAll()) {
            beans.add(new FutureProductBean(item));
        }
        ftm.setData(beans);
    }

