    @Override
    protected void fillModelList() {
        // Crea e setta il model
        FutureProductBean prototype = new FutureProductBean(null);
        FutureProductTableModel model = new FutureProductTableModel(prototype);
        productTable.setModel(model);

        // Popola il model
        refreshModel(model);
    }

    @Override
    protected void acNewActionPerformed(ActionEvent evt) {
        openDialog(null);
    }

    @Override
    protected void acModActionPerformed(ActionEvent evt) {
        FutureProductBean bean = selectedBean();
        if (bean != null) {
            openDialog(bean);
        }
    }

    private void openDialog(FutureProductBean bean) {
        java.awt.Window parentWindow = javax.swing.SwingUtilities.getWindowAncestor(this);
        java.awt.Frame parentFrame = null;

        if (parentWindow instanceof java.awt.Frame frame) {
            parentFrame = frame;
        }

        FutureProductDlg dialog = new FutureProductDlg(parentFrame, true, bean, masterDataFacade);
        dialog.setSize(600, 540);
        // Centra la dialog rispetto al pannello
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        // Post chiusura dialog
        refreshModel((FutureProductTableModel) productTable.getModel());
    }

    @Override
    protected void acDelActionPerformed(ActionEvent evt) {
        FutureProductBean bean = selectedBean();
        if (bean != null) {
            FutureProduct fp = bean.getFutureProduct();
            if (JOptionPane.showConfirmDialog(this,
                    "Are you sure to delete item? " + fp.getCode(), JMasterDataMgr.TITLE,
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.QUESTION_MESSAGE) == JOptionPane.YES_OPTION) {
                try {
                    masterDataFacade.getFutureProductDAO().delete(fp);
                    refreshModel((FutureProductTableModel) productTable.getModel());
                } catch (Exception ex) {
                    LoggerMgr.logError(ex.getLocalizedMessage());
                    JOptionPane.showMessageDialog(this, ex.getLocalizedMessage(),
                            JMasterDataMgr.TITLE, JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }

    private FutureProductBean selectedBean() {
        int rowIndex = productTable.getSelectedRow();
        if (rowIndex == -1) {
            return null;
        }
        int modelRow = productTable.convertRowIndexToModel(rowIndex);
        return ((FutureProductTableModel) productTable.getModel()).getElementAt(modelRow);
    }

