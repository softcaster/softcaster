    private void postInit() {
        cbType.setModel(new DefaultComboBoxModel<>(ProductKind.values()));
        cbCurrency.setModel(new DefaultComboBoxModel<>(masterDataFacade.getCurrencyDAO().findAll().toArray(Currency[]::new)));
        cbSettlementType.setModel(new DefaultComboBoxModel<>(SettlementType.values()));
        cbUnderlying.setModel(new DefaultComboBoxModel<>(masterDataFacade.getForexMasterDataDAO().findAll().toArray(ForexMasterData[]::new)));
        cbLoadType.setModel(new DefaultComboBoxModel<>(LoadType.values()));

        if (bean == null) {
            cbType.setSelectedIndex(-1);
            cbCurrency.setSelectedIndex(-1);
            setUpSpecificFields(null);
        } else {
            isInsert = false;
            FutureProduct fp = (FutureProduct) Hibernate.unproxy(bean.getFutureProduct());
            cbType.setSelectedItem(ProductKind.of(fp));
            txtCode.setText(fp.getCode());
            txtDescription.setText(fp.getDescription());
            txtExchangeCode.setText(fp.getExchangeContractCode());
            txtAssetClass.setText(fp.getAssetClass().getCode());
            FutureProductHelper.selectById(cbCurrency, fp.getCurrency().getIdCurrency(), Currency::getIdCurrency);
            cbSettlementType.setSelectedItem(fp.getSettlementType());
            txtBusinessDays.setText(fp.getBusinessDays() == null ? "" : fp.getBusinessDays().toString());
            txtContractValue.setText(FutureProductHelper.format(fp.getContractValue()));
            txtTickSize.setText(FutureProductHelper.format(fp.getTickSize()));
            txtInitMargin.setText(FutureProductHelper.format(fp.getInitialMargin()));
            txtMaintMargin.setText(FutureProductHelper.format(fp.getMaintenanceMargin()));
            txtMultiplier.setText(FutureProductHelper.format(fp.getMultiplier()));
            if (fp instanceof FxFutureProduct fx) {
                FutureProductHelper.selectById(cbUnderlying, fx.getUnderlying().getIdMasterData(), ForexMasterData::getIdMasterData);
            } else if (fp instanceof MmFutureProduct mm) {
                FutureProductHelper.selectById(cbUnderlying, mm.getUnderlying().getIdMasterData(), ForexMasterData::getIdMasterData);
            }
            if (fp instanceof CmdFutureProduct cmd) {
                cbCommodityType.setSelectedItem(cmd.getCommodityType());
            }
            if (fp instanceof PowerFutureProduct power) {
                cbLoadType.setSelectedItem(power.getLoadType());
            }
            // codice e tipo identificano la testata; valuta, business days e multiplier
            // sono copiati nelle scadenze: fissi solo se la testata e' gia' usata
            FutureProductHelper.lock(txtCode, cbType);
            if (masterDataFacade.getFutureProductDAO().countReferences(fp) > 0) {
                FutureProductHelper.lock(cbCurrency, txtBusinessDays, txtMultiplier);
            }
        }

        // obbligatori in future_product (il margine di mantenimento no)
        fieldsToValidate = Arrays.asList(txtCode, txtDescription, txtContractValue, txtTickSize,
                txtInitMargin, txtBusinessDays, txtMultiplier);
    }

    /**
     * Mostra solo i campi specifici del tipo: coppia di cambi (Fx, Mm),
     * commodity (Cmd, Power: solo quelle a consegna estesa), load type
     * (Power).
     */
    private void setUpSpecificFields(ProductKind kind) {
        boolean underlying = kind == ProductKind.FX || kind == ProductKind.MM;
        boolean commodity = kind == ProductKind.CMD || kind == ProductKind.POWER;
        boolean load = kind == ProductKind.POWER;

        CommodityType selected = (CommodityType) cbCommodityType.getSelectedItem();
        cbCommodityType.setModel(new DefaultComboBoxModel<>(Arrays.stream(CommodityType.values())
                .filter(c -> c.isExtendedDelivery() == load)
                .toArray(CommodityType[]::new)));
        cbCommodityType.setSelectedItem(commodity ? selected : null);

        jLabel14.setVisible(underlying);
        cbUnderlying.setVisible(underlying);
        jLabel15.setVisible(commodity);
        cbCommodityType.setVisible(commodity);
        jLabel16.setVisible(load);
        cbLoadType.setVisible(load);
        if (!underlying) {
            cbUnderlying.setSelectedIndex(-1);
        }
        if (!load) {
            cbLoadType.setSelectedIndex(-1);
        }
    }

    /**
     * @return il messaggio d'errore, null se i dati sono corretti
     */
    private String validateIntegrity() {
        ProductKind kind = (ProductKind) cbType.getSelectedItem();
        if (kind == null || cbCurrency.getSelectedItem() == null || cbSettlementType.getSelectedItem() == null) {
            return "Please select type, currency and settlement type.";
        }
        if (isInsert && masterDataFacade.getFutureProductDAO().findByCode(txtCode.getText().trim()).isPresent()) {
            return "Product " + txtCode.getText().trim() + " already exists.";
        }
        if ((kind == ProductKind.FX || kind == ProductKind.MM) && cbUnderlying.getSelectedItem() == null) {
            return "Please select the underlying currency pair.";
        }
        if ((kind == ProductKind.CMD || kind == ProductKind.POWER) && cbCommodityType.getSelectedItem() == null) {
            return "Please select the commodity type.";
        }
        if (kind == ProductKind.POWER && cbLoadType.getSelectedItem() == null) {
            return "Please select the load type.";
        }
        try {
            Integer.valueOf(txtBusinessDays.getText().trim());
            for (javax.swing.JTextField f : List.of(txtContractValue, txtTickSize, txtMultiplier, txtInitMargin, txtMaintMargin)) {
                parse(f);
            }
        } catch (NumberFormatException | ParseException ex) {
            return "Please check the numeric fields.";
        }
        return null;
    }

    private static Double parse(javax.swing.JTextField field) throws ParseException {
        return field.getText().isBlank() ? null : Converter.toDouble(field.getText(), false);
    }

    private boolean saveBean() {
        try {
            ProductKind kind = (ProductKind) cbType.getSelectedItem();
            FutureProduct fp;
            if (isInsert) {
                fp = kind.factory.get();
                fp.setCode(txtCode.getText().trim());
                fp.setAssetClass(masterDataFacade.findAssetClass(kind.assetClass));
            } else {
                fp = (FutureProduct) Hibernate.unproxy(bean.getFutureProduct());
            }
            // bloccati in modifica se la testata ha gia' scadenze: restano invariati
            fp.setCurrency((Currency) cbCurrency.getSelectedItem());
            fp.setBusinessDays(Integer.valueOf(txtBusinessDays.getText().trim()));
            fp.setMultiplier(parse(txtMultiplier));
            fp.setDescription(txtDescription.getText().trim());
            // il codice di borsa, se non indicato, e' il codice della testata
            fp.setExchangeContractCode(txtExchangeCode.getText().isBlank() ? fp.getCode() : txtExchangeCode.getText().trim());
            fp.setSettlementType((SettlementType) cbSettlementType.getSelectedItem());
            fp.setContractValue(parse(txtContractValue));
            fp.setTickSize(parse(txtTickSize));
            fp.setInitialMargin(parse(txtInitMargin));
            fp.setMaintenanceMargin(parse(txtMaintMargin));
            if (fp instanceof FxFutureProduct fx) {
                fx.setUnderlying((ForexMasterData) cbUnderlying.getSelectedItem());
            } else if (fp instanceof MmFutureProduct mm) {
                mm.setUnderlying((ForexMasterData) cbUnderlying.getSelectedItem());
            }
            if (fp instanceof CmdFutureProduct cmd) {
                cmd.setCommodityType((CommodityType) cbCommodityType.getSelectedItem());
            }
            if (fp instanceof PowerFutureProduct power) {
                power.setLoadType((LoadType) cbLoadType.getSelectedItem());
            }
            masterDataFacade.getFutureProductDAO().saveOrUpdate(fp);
            return true;
        } catch (Exception ex) {
            LoggerMgr.logError(ex.getLocalizedMessage());
            return false;
        }
    }
