    private static final String MONTH_CODES = "FGHJKMNQUVXZ";

    /**
     * Codice della serie nel formato CME: testata + mese + ultima cifra
     * dell'anno + "_" + C/P + cifre dello strike senza punto, completate con
     * zeri fino a 4 (EUU, dic-2026, call 1,14 -> "EUUZ6_C1140"; strike 1,345
     * -> "EUUZ6_C1345"). Convenzione di questa finestra: l'anagrafica non la
     * conosce, altre viste (Eurex, IDEM, OTC) gestiranno codice e ISIN a modo
     * loro.
     */
    static String cmeSeriesCode(String productCode, LocalDate expiryMonth, OptionType type, double strike) {
        StringBuilder digits = new StringBuilder(java.math.BigDecimal.valueOf(strike).stripTrailingZeros().toPlainString().replace(".", ""));
        while (digits.length() < 4) {
            digits.append('0');
        }
        return productCode + MONTH_CODES.charAt(expiryMonth.getMonthValue() - 1) + (expiryMonth.getYear() % 10)
                + "_" + (type == OptionType.CALL ? "C" : "P") + digits;
    }

    /**
     * Codice della serie nel formato CME (EUUZ6_C1140), usato anche come ISIN;
     * vuoto finche' mancano testata, scadenza o strike.
     */
    private Optional<String> seriesCode() {
        try {
            String productCode = txtProductCode.getText().trim();
            if (productCode.isEmpty() || txtExpiryDate.getText().isBlank() || txtStrike.getText().isBlank()) {
                return Optional.empty();
            }
            LocalDate expiry = new Date(txtExpiryDate.getText()).sqlDate().toLocalDate();
            double strike = Converter.toDouble(txtStrike.getText(), false);
            return Optional.of(cmeSeriesCode(productCode, expiry, (OptionType) cbOptionType.getSelectedItem(), strike));
        } catch (Exception ex) {
            return Optional.empty();
        }
    }

    private void refreshCode() {
        String code = seriesCode().orElse("");
        txtCode.setText(code);
        txtIsin.setText(code);
    }

    private String selectedAssetClass() {
        AssetClass ac = (AssetClass) cbAssetClass.getSelectedItem();
        return ac == null ? "" : ac.getCode();
    }

    /**
     * Testate di future proponibili come sottostante: solo per le opzioni su
     * future (FFO: FX future, BFO: bond future); per le altre famiglie solo
     * "nessuna" (sottostante secco).
     */
    private void setUpFutureProductCombo() {
        Class<? extends FutureProduct> type = switch (selectedAssetClass()) {
            case "FFO" -> FxFutureProduct.class;
            case "BFO" -> BondFutureProduct.class;
            default -> null;
        };
        List<FutureProduct> products = new ArrayList<>();
        if (type == null) {
            products.add(null);
        } else {
            products.addAll(masterDataFacade.getFutureProductDAO().findAll(type));
        }
        cbFutureProduct.setModel(new DefaultComboBoxModel<>(products.toArray(FutureProduct[]::new)));
    }

    /**
     * Sottostanti proponibili, non scaduti: le scadenze del future scelto per
     * le opzioni su future, altrimenti gli strumenti secchi della famiglia
     * (FXO: coppie di cambi, BDO: titoli). La serie in modifica conserva il
     * proprio sottostante anche se scaduto.
     */
    private void setUpUnderlyingCombo() {
        FutureProduct fp = (FutureProduct) cbFutureProduct.getSelectedItem();
        MasterData selected = (MasterData) cbUnderlying.getSelectedItem();
        MasterData current = bean == null ? null : bean.getOptionMasterData().getUnderlying();
        String ac = selectedAssetClass();
        List<MasterData> candidates = allMasterData.stream()
                .filter(md -> current != null && md.getIdMasterData().equals(current.getIdMasterData())
                || !isExpired(md) && switch (ac) {
                    case "FFO", "BFO" -> fp != null && md instanceof FutureMasterData fmd && fmd.getProduct() != null
                    && fp.getIdFutureProduct().equals(fmd.getProduct().getIdFutureProduct());
                    case "FXO" -> md instanceof ForexMasterData;
                    case "BDO" -> md instanceof SecurityMasterData;
                    default -> false;
                })
                .toList();
        cbUnderlying.setModel(new DefaultComboBoxModel<>(candidates.toArray(MasterData[]::new)));
        if (selected != null) {
            selectUnderlying(selected);
        }
    }

    private boolean isExpired(MasterData md) {
        return officialDate != null && md.getMaturityDate() != null
                && md.getMaturityDate().toLocalDate().isBefore(officialDate);
    }
    private void selectFutureProduct(FutureProduct fp) {
        Integer id = fp == null ? null : fp.getIdFutureProduct();
        for (int i = 0; i < cbFutureProduct.getItemCount(); i++) {
            FutureProduct item = cbFutureProduct.getItemAt(i);
            if (Objects.equals(id, item == null ? null : item.getIdFutureProduct())) {
                cbFutureProduct.setSelectedIndex(i);
                break;
            }
        }
        setUpUnderlyingCombo();
    }

    private void selectUnderlying(MasterData md) {
        if (md == null) {
            return;
        }
        for (int i = 0; i < cbUnderlying.getItemCount(); i++) {
            if (md.getIdMasterData().equals(cbUnderlying.getItemAt(i).getIdMasterData())) {
                cbUnderlying.setSelectedIndex(i);
                return;
            }
        }
    }

    private static void selectByCode(javax.swing.JComboBox<AssetClass> combo, String code) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).getCode().equals(code)) {
                combo.setSelectedIndex(i);
                return;
            }
        }
    }

