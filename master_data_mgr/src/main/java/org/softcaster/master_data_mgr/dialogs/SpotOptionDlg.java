    private void selectProduct(SpotOptionProduct p) {
        for (int i = 0; i < cbProduct.getItemCount(); i++) {
            if (cbProduct.getItemAt(i).getIdOptionProduct().equals(p.getIdOptionProduct())) {
                cbProduct.setSelectedIndex(i);
                return;
            }
        }
    }
