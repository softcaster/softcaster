    private String selectedAssetClass() {
        AssetClass ac = (AssetClass) cbAssetClass.getSelectedItem();
        return ac == null ? "" : ac.getCode();
    }

    private boolean futureKind() {
        return FutureOptionProduct.FUTURE_PRODUCT_TYPES.containsKey(selectedAssetClass());
    }

    /**
     * Future sottostante (opzioni su future) o sottostante fisso (opzioni su
     * strumento secco) secondo l'asset class.
     */
    private void refreshKind() {
        String ac = selectedAssetClass();
        Class<? extends FutureProduct> futureType = FutureOptionProduct.FUTURE_PRODUCT_TYPES.get(ac);
        List<FutureProduct> futures = new ArrayList<>();
        if (futureType != null) {
            futures.addAll(masterDataFacade.getFutureProductDAO().findAll(futureType));
        }
        cbFutureProduct.setModel(new DefaultComboBoxModel<>(futures.toArray(FutureProduct[]::new)));
        cbFutureProduct.setEnabled(futureType != null);

        Class<? extends MasterData> underlyingType = SpotOptionProduct.UNDERLYING_TYPES.get(ac);
        List<MasterData> underlyings = new ArrayList<>();
        underlyings.add(null);   // nessun sottostante fisso
        if (underlyingType != null) {
            allMasterData.stream().filter(md -> underlyingType.isInstance(Hibernate.unproxy(md))).forEach(underlyings::add);
        }
        cbFixedUnderlying.setModel(new DefaultComboBoxModel<>(underlyings.toArray(MasterData[]::new)));
        cbFixedUnderlying.setEnabled(underlyingType != null);
    }

    /**
     * Salva la testata.
     *
     * @return null se tutto ok, altrimenti il messaggio di errore
     */
    private String saveProduct() {
        try {
            AssetClass assetClass = (AssetClass) cbAssetClass.getSelectedItem();
            if (assetClass == null) {
                return "Missing asset class: add the option families (FFO, BFO, FXO, BDO) to asset_class";
            }
            String code = txtCode.getText().trim();
            if (product == null && masterDataFacade.getOptionProductDAO().findByCode(code).isPresent()) {
                return "Product " + code + " already exists";
            }
            LocalTime expiryTime = txtExpiryTime.getText().isBlank() ? null
                    : LocalTime.parse(txtExpiryTime.getText().trim(), TIME_INPUT_FORMAT);
            String zone = txtTimeZone.getText().trim();
            if (!zone.isEmpty()) {
                ZoneId.of(zone); // fuso IANA valido (America/New_York, Europe/Rome)
            }

            OptionProduct p = product;
            if (p == null) {
                p = futureKind() ? new FutureOptionProduct() : new SpotOptionProduct();
                p.setCode(code);
                p.setAssetClass(assetClass);
                p.setCurrency((Currency) cbCurrency.getSelectedItem());
                p.setMultiplier(Converter.toDouble(txtMultiplier.getText(), false));
                p.setBusinessDays(Integer.valueOf(txtBusinessDays.getText().trim()));
            }
            p.setDescription(txtDescription.getText().isBlank() ? code : txtDescription.getText());
            p.setExchangeContractCode(txtExchangeCode.getText().isBlank() ? code : txtExchangeCode.getText().trim());
            p.setExerciseStyle((ExerciseStyle) cbExerciseStyle.getSelectedItem());
            p.setPremiumStyle((PremiumStyle) cbPremiumStyle.getSelectedItem());
            p.setSettlementType((SettlementType) cbSettlementType.getSelectedItem());
            p.setContractValue(Converter.toDouble(txtContractValue.getText(), false));
            p.setTickSize(Converter.toDouble(txtTickSize.getText(), false));
            p.setInitialMargin(txtInitMargin.getText().isBlank() ? null : Converter.toDouble(txtInitMargin.getText(), false));
            p.setMaintenanceMargin(txtMaintMargin.getText().isBlank() ? null : Converter.toDouble(txtMaintMargin.getText(), false));
            p.setExpiryTime(expiryTime);
            p.setExpiryTimeZone(zone.isEmpty() ? null : zone);

            if (p instanceof FutureOptionProduct fop) {
                FutureProduct future = (FutureProduct) cbFutureProduct.getSelectedItem();
                if (future == null) {
                    return "Missing underlying future";
                }
                fop.setFutureProduct(future);
            } else if (p instanceof SpotOptionProduct sop) {
                MasterData fixed = (MasterData) cbFixedUnderlying.getSelectedItem();
                // sottostante fisso: le serie esistenti devono gia' averlo
                if (fixed != null && sop.getIdOptionProduct() != null) {
                    for (SpotOptionMasterData s : masterDataFacade.getSpotOptionMasterDataDAO().findAll()) {
                        if (Objects.equals(s.getProduct().getIdOptionProduct(), sop.getIdOptionProduct())
                                && !s.getUnderlying().getIdMasterData().equals(fixed.getIdMasterData())) {
                            return "Series " + s.getCode() + " has underlying " + s.getUnderlying().getCode()
                                    + ": it cannot be fixed to " + fixed.getCode();
                        }
                    }
                }
                sop.setUnderlying(fixed);
            }
            masterDataFacade.getOptionProductDAO().saveOrUpdate(p);
            return null;
        } catch (Exception ex) {
            LoggerMgr.logError(ex.getLocalizedMessage());
            Throwable t = ex;
            while (t.getCause() != null) {
                t = t.getCause();
            }
            return "Error during save: " + t.getLocalizedMessage();
        }
    }

    private void selectByCode(String code) {
        for (int i = 0; i < cbAssetClass.getItemCount(); i++) {
            if (cbAssetClass.getItemAt(i).getCode().equals(code)) {
                cbAssetClass.setSelectedIndex(i);
                return;
            }
        }
    }

    private static void selectById(javax.swing.JComboBox<FutureProduct> combo, Integer id) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (Objects.equals(id, combo.getItemAt(i).getIdFutureProduct())) {
                combo.setSelectedIndex(i);
                return;
            }
        }
    }

    private void selectMasterData(MasterData md) {
        for (int i = 0; i < cbFixedUnderlying.getItemCount(); i++) {
            MasterData item = cbFixedUnderlying.getItemAt(i);
            if (item != null && item.getIdMasterData().equals(md.getIdMasterData())) {
                cbFixedUnderlying.setSelectedIndex(i);
                return;
            }
        }
    }

    /**
     * Codici di anagrafiche, testate di future e asset class nelle combo.
     */
    private static class CodeRenderer extends DefaultListCellRenderer {

        @Override
        public Component getListCellRendererComponent(JList<?> list, Object value, int index,
                boolean isSelected, boolean cellHasFocus) {
            Object text = value;
            if (value == null) {
                text = " ";
            } else if (value instanceof MasterData md) {
                text = md.getCode() + (md.getDescription() == null || md.getDescription().isBlank() ? "" : " - " + md.getDescription());
            } else if (value instanceof FutureProduct fp) {
                text = fp.getCode() + " - " + fp.getDescription();
            } else if (value instanceof AssetClass ac) {
                text = ac.getCode() + " - " + ac.getDescription();
            }
            return super.getListCellRendererComponent(list, text, index, isSelected, cellHasFocus);
        }
    }
