            txtContractValue.setText(product.getContractValue() == null ? "" : Converter.fromDouble(product.getContractValue()));
            txtTickSize.setText(product.getTickSize() == null ? "" : Converter.fromDouble(product.getTickSize()));
            txtMultiplier.setText(Converter.fromDouble(product.getMultiplier()));
            txtMultiplier.setEditable(false);
